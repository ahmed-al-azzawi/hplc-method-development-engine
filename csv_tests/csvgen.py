    lines.append("Output Time,10:00:00 AM")
    lines.append("")
    lines.append("[File Information]")
    lines.append("Type,Data File")
    lines.append("Generated,27/10/2026 09:30:00 AM")
    lines.append("Generated by,System Administrator")
    lines.append("")
    lines.append("[Sample Information]")
    lines.append("Operator Name,System Administrator")
    lines.append(f"Sample Name,{sample_name}")
    lines.append("Sample ID,mock_test_run")
    for i in range(1, 15):
        lines.append(f"ISTD Amount{i},1")
    lines.append("")
    lines.append("[Original Files]")
    lines.append(f"Data File,C:\\LabSolutions\\MockData\\{sample_name}.lcd")
    lines.append("Method File,C:\\LabSolutions\\MockData\\Method.lcm")
    lines.append("")
    lines.append("[Configuration]")
    lines.append("Instrument Name,Instrument1")
    lines.append("Instrument #,1")
    lines.append("Line #,1")
    lines.append("# of Detectors,1")
    lines.append("Detector ID,Detector A")
    lines.append("")

    # Peak Table Header & Rows
    lines.append("[Peak Table(Detector A)]")
    lines.append(f"# of Peaks,{len(peaks_data)}")
    lines.append(
        "Peak#,R.Time,I.Time,F.Time,Area,Height,A/H,Conc.,Mark,ID#,Name,k',Plate #,Plate Ht.,Tailing,Resolution,Sep.Factor,Area Ratio,Height Ratio,Conc. %,Norm Conc."
    )

    for p in peaks_data:
        p_num, rt, it, ft, area, height, res = p
        lines.append(
            f"{p_num},{rt:.3f},{it:.3f},{ft:.3f},{area},{height},5.0,14.2,SV ,,,0.0,5000,20.0,1.1,{res:.3f},1.2,0,0,0.0,0.0"
        )

    lines.append("")
    lines.append("[Compound Results(Detector A)]")
    lines.append("# of IDs,0")
    lines.append("")
    lines.append("[Group Results(Detector A)]")
    lines.append("# of Groups,0")
    lines.append("")
    lines.append("[Slice Data(Detector A)]")
    lines.append("# of Slices,0")
    lines.append("")

    # LC Chromatogram Trace (UV)
    time_pts = np.arange(0, total_time, 0.01)
    lines.append("[LC Chromatogram(Detector A-Ch1)]")
    lines.append("Interval(msec),500")
    lines.append(f"# of Points,{len(time_pts)}")
    lines.append("Start Time(min),0.000")
    lines.append(f"End Time(min),{total_time:.3f}")
    lines.append("Intensity Units,mAU")
    lines.append("Intensity Multiplier,1.0")

    for t in time_pts:
        uv_val = 10.0  # baseline
        for p in peaks_data:
            _, rt, _, _, _, height, _ = p
            uv_val += height * np.exp(-((t - rt) ** 2) / (2 * 0.05**2))
        lines.append(f"{t:.3f},{int(uv_val)}")

    lines.append("")
    # Backpressure Status Trace
    lines.append("[LC Status Trace(Pump A Pressure)]")
    lines.append("Interval(msec),1000")
    lines.append(f"# of Points,{len(time_pts)//2}")
    lines.append("Start Time(min),0.000")
    lines.append(f"End Time(min),{total_time:.3f}")
    lines.append("Intensity Units,psi")
    lines.append("Intensity Multiplier,0.001")

    for t in time_pts[::2]:
        if is_gradient:
            p_val = calculate_gradient_viscosity_profile(
                t,
                t_hold_init=3.0,
                t_ramp=total_time - 8.0,
                t_hold_final=3.0,
                b_init=5.0,
                b_final=100.0,
                flow_rate=1.5,
                column_vol=1.5,
                base_bp=2200.0,
            )
        else:
            p_val = 2500.0

        lines.append(f"{t:.3f},{int(p_val * 1000)}")

    lines.append("")
    lines.append("[LC Status Trace(Pump A Degasser Pressure)]")
    lines.append("# of Points,0")

    with open(filename, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Generated: {filename}")


